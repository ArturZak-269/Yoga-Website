/* ── Language state ── */
let currentLanguage = localStorage.getItem('lang') || 'pl';

function translatePage() {
  const lang = translations[currentLanguage] || translations.pl;

  document.querySelectorAll('[data-translate]').forEach(el => {
    const key = el.getAttribute('data-translate');
    if (lang[key] !== undefined) {
      el.textContent = lang[key];
    }
  });

  /* Sync flag active state — desktop + mobile */
  ['plFlag', 'enFlag', 'uaFlag', 'plFlagMobile', 'enFlagMobile', 'uaFlagMobile'].forEach(id => {
    const btn = document.getElementById(id);
    if (!btn) return;
    const langCode = id.replace('Flag', '').replace('Mobile', '');
    btn.classList.toggle('active-flag', langCode === currentLanguage);
  });
}

function setLanguage(lang) {
  currentLanguage = lang;
  localStorage.setItem('lang', lang);
  translatePage();
}

/* ── Flag click listeners (desktop + mobile) ── */
['pl', 'en', 'ua'].forEach(lang => {
  const desktop = document.getElementById(lang + 'Flag');
  const mobile  = document.getElementById(lang + 'FlagMobile');
  if (desktop) desktop.addEventListener('click', () => setLanguage(lang));
  if (mobile)  mobile.addEventListener('click',  () => setLanguage(lang));
});

/* Run on load */
translatePage();
